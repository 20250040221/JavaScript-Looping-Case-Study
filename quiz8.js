
let age = 15;

if (age < 0) {
    console.log("Invalid age");
} else if (age <= 5) {
    console.log("Toddler");
} else if (age <= 12) {
    console.log("Child");
} else if (age <= 17) {
    console.log("Teenager");
} else if (age <= 59) {
    console.log("Adult");
} else {
    console.log("Senior");
}
